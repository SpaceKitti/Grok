    def lam_max(k):
        return bb**2 / (3 * aa * cc * k * k)

    def lam_flat(k):
        return bb**2 / (4 * aa * cc * k * k)

    def onshell(Lv, k):
        D = bb * bb - 3 * aa * cc * Lv * k * k
        if not (Lv > 0 and D > 0):
            return None
        xm = 3 * cc * k * k / (bb + math.sqrt(D))
        fl = cc * k * k / xm**3
        la = aa * Lv / xm
        cu = bb / xm**2
        Vm = la - cu + fl
        vxx = 2 * aa * Lv / xm**3 - 6 * bb / xm**4 + 12 * cc * k * k / xm**5
        return {"x": xm, "p_flux": fl / (fl + la), "p_curv": fl / (fl + la + cu), "V": Vm, "Vform": (bb * xm - 2 * cc * k * k) / xm**3, "Vscale": la + cu + fl, "vxx": vxx, "B2half": fl / (aa / xm)}

