    cc = float(sp.N(c.subs(g6, G6_NUM)))
    w("Numeric convention [assumed input]: M_6 = %.1f, g_6 = %.1f, so a = %.9f, b = %.9f, c = %.9f, c/b = %.6f." % (M6_NUM, G6_NUM, aa, bb, cc, cc / bb))
