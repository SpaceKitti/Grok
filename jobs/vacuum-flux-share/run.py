def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def snapshot(root: Path):
    return {str(p.relative_to(root)): sha(p) for p in sorted(root.rglob("*")) if p.is_file()}


def parse_j3_bands(path: Path):
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\| band (\d+) \| ([0-9.]+) \| ([0-9.]+) \|\s*$", line)
        if m:
            rows.append((int(m.group(1)), float(m.group(2)), float(m.group(3))))
    if not rows:
        raise RuntimeError("Job Three p-band table not found")
    return [(lo, hi) for _, lo, hi in sorted(rows)]


def parse_j5_bands(path: Path):
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\| (\d) \| \[([0-9.]+), ([0-9.]+)\] \| \[([-0-9.]+), ([-0-9.]+)\] \|", line)
        if m:
            rows.append((int(m.group(1)), float(m.group(2)), float(m.group(3))))
    return [(lo, hi) for _, lo, hi in sorted(rows)]


def fmt_iv(lo, hi, nd=6):
    return "[%.*f, %.*f]" % (nd, lo, nd, hi)


