                full = np.zeros(free.size)
                full[free] = vec
                Mn = tt.size
                wt = np.full(Mn, H_FL)
                wt[0] = wt[-1] = H_FL / 2
                amp = np.r_[bn["f"], np.zeros(Mn)]
                Md = np.r_[wt * bn["Om2"], wt * bn["Om2"]]
                ovl[(n, eps)] = float((full @ (Md * amp)) ** 2 / ((full @ (Md * full)) * (amp @ (Md * amp))))
