# ---------------- background: Taubes BVP in t ----------------
def logsig2(tt):          # log sin^2(theta/2) = log sigma(2t)
    return -np.logaddexp(0.0, -2.0 * tt)


def logcos2(tt):          # log cos^2(theta/2)
    return -np.logaddexp(0.0, 2.0 * tt)


def sech2(tt):
    return np.exp(2.0 * (math.log(2.0) - np.logaddexp(tt, -tt)))


def solve_bg(n, p, R2, guess=None):
    """u'' = sech^2 t (n - R^2 + R^2 sin^{2p}(theta/2) cos^{2(n-p)}(theta/2) e^u), u'(+-T) = 0."""
    def lw(tt):
        return p * logsig2(tt) + (n - p) * logcos2(tt)

    def f(tt, y):
        s2 = sech2(tt)
        return np.vstack([y[1], s2 * (n - R2 + R2 * np.exp(lw(tt) + y[0]))])

    def jac(tt, y):
        s2 = sech2(tt)
        J = np.zeros((2, 2, tt.size))
        J[0, 1] = 1.0
        J[1, 0] = s2 * R2 * np.exp(lw(tt) + y[0])
        return J

    bc = lambda ya, yb: np.array([ya[1], yb[1]])
    bcj = lambda ya, yb: (np.array([[0.0, 1.0], [0.0, 0.0]]), np.array([[0.0, 0.0], [0.0, 1.0]]))
    tt = np.linspace(-T_BVP, T_BVP, N_BVP0)
    if guess is None:
        y0 = np.zeros((2, tt.size))
    else:
        y0 = guess(tt)
    s = solve_bvp(f, bc, tt, y0, fun_jac=jac, bc_jac=bcj, tol=BVP_TOL, max_nodes=2_000_000)
    return s, lw


def bg_fields(sol, lw, n, p, R2, tt):
    y = sol.sol(tt)
    u, up = y[0], y[1]
    h = lw(tt) + u
    sig = np.exp(logsig2(tt))
    hp = 2 * p * (1 - sig) - 2 * (n - p) * sig + up
    f = np.exp(h / 2)
    Om2 = R2 * sech2(tt)
    return dict(u=u, up=up, h=h, hp=hp, f=f, f2=np.exp(h), Om2=Om2, Om=np.sqrt(Om2))


def integrals(sol, lw, n, p, R2):
    tt = np.linspace(-T_BVP, T_BVP, N_QUAD)
    b = bg_fields(sol, lw, n, p, R2, tt)
    phi2 = 2 * np.pi * simpson(b["Om2"] * b["f2"], x=tt)
    E = 2 * np.pi * simpson(b["f2"] * b["hp"] ** 2 / 4 + b["Om2"] * (1 - b["f2"]) ** 2 / 4, x=tt)
    return phi2, E, float(np.max(b["f2"]))


# ---------------- fluctuation operator, sector k ----------------
def sector_matrices(bgfun, n, p, k, H, T):
    """Real sector-k form of the background-gauge Hessian K = int |P|^2 + |S/Omega|^2 dt, mass M = int Omega^2(|eta|^2 + |b|^2) dt.
    eta ~ e^{i(p+k)phi} (regular gauge at N), alpha = a_t + i a_phi = i Omega b e^{ik phi}.
    P = eta' - nu eta + f Omega b,  S/Omega = b' + (k - tanh t) b + Omega f eta,  nu = k + h'/2."""
    tt = np.arange(-T, T + H / 2, H)
    Mn = tt.size
    th_ = 0.5 * (tt[1:] + tt[:-1])
    bh = bgfun(th_)
    bn = bgfun(tt)
    nu = k + bh["hp"] / 2
    fO = bh["f"] * bh["Om"]
    km = k - np.tanh(th_)
    J = Mn - 1
    rows = np.arange(J)
    Dm = sps.csr_matrix((np.r_[-np.ones(J), np.ones(J)] / H, (np.r_[rows, rows], np.r_[rows, rows + 1])), shape=(J, Mn))
    Av = sps.csr_matrix((np.full(2 * J, 0.5), (np.r_[rows, rows], np.r_[rows, rows + 1])), shape=(J, Mn))
    Pe = Dm - sps.diags(nu) @ Av
    Pb = sps.diags(fO) @ Av
    Se = sps.diags(fO) @ Av
    Sb = Dm + sps.diags(km) @ Av
    Lmat = sps.bmat([[Pe, Pb], [Se, Sb]]).tocsr()
    wt = np.full(Mn, H)
    wt[0] = wt[-1] = H / 2
    Mdiag = np.r_[wt * bn["Om2"], wt * bn["Om2"]]
    free = np.ones(2 * Mn, bool)
    if p + k != 0:
        free[0] = False                 # eta Dirichlet at N
    if p + k - n != 0:
        free[Mn - 1] = False            # eta Dirichlet at S (regular-gauge index p + k - n)
    if k != -1:
        free[Mn] = False                # b Dirichlet at N
    if k != 1:
        free[2 * Mn - 1] = False        # b Dirichlet at S
    Lf = Lmat[:, free]
    K = (H * (Lf.T @ Lf)).tocsc()
    Mm = sps.diags(Mdiag[free]).tocsc()
    return K, Mm, free, tt, bn


def lowest(K, Mm, nev=NEV):
    w, v = spla.eigsh(K, k=nev, M=Mm, sigma=-1e-3, which="LM")
    o = np.argsort(w)
    return w[o], v[:, o]


# ---------------- C2: symmetric phase -D^2 ----------------
def symmetric_spectrum(n, R2, m, H, T, nev):
    tt = np.arange(-T, T + H / 2, H)
    Mn = tt.size
    Aphi = 0.5 * n * (1 + np.tanh(tt))       # uniform B = n/(2R^2): F_flat = Omega^2 B, A_phi(-inf) = 0
    th_ = 0.5 * (tt[1:] + tt[:-1])
    J = Mn - 1
    rows = np.arange(J)
    Dm = sps.csr_matrix((np.r_[-np.ones(J), np.ones(J)] / H, (np.r_[rows, rows], np.r_[rows, rows + 1])), shape=(J, Mn))
    wt = np.full(Mn, H)
    wt[0] = wt[-1] = H / 2
    K = H * (Dm.T @ Dm) + sps.diags(wt * (m - Aphi) ** 2)
    Mdiag = wt * R2 * sech2(tt)
    free = np.ones(Mn, bool)
    if m != 0:
        free[0] = False
    if m != n:
        free[-1] = False
    K = K.tocsr()[free][:, free].tocsc()
    Mm = sps.diags(Mdiag[free]).tocsc()
    w = spla.eigsh(K, k=nev, M=Mm, sigma=-1e-3, which="LM")[0]
    return np.sort(w)


