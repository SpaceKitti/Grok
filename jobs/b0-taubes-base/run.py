def plane_profile(n):
    sl_ = np.log(PLANE_RMAX)
    def f(ss, y):
        return np.vstack([y[1], np.exp(2 * ss) * (np.exp(2 * n * ss + y[0]) - 1)])
    bc = lambda ya, yb: np.array([ya[1], yb[0] + 2 * n * sl_])
    ss = np.linspace(-T_BVP, sl_, N_BVP0)
    y0 = np.vstack([-2 * n * np.log1p(np.exp(ss)) , np.zeros(ss.size)])
    return solve_bvp(f, bc, ss, y0, tol=BVP_TOL, max_nodes=2_000_000)


